function initialLang(): string {
  try {
    const saved = localStorage.getItem('a320.lang');
    if (saved === 'en' || saved === 'zh-TW') return saved;
  } catch {
    // 私密模式：忽略
  }
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh-TW' : 'en';
}

void i18n.use(initReactI18next).init({
  resources: { en: { translation: en }, 'zh-TW': { translation: zh } },
  lng: initialLang(),
  fallbackLng: 'en',
  interpolation: { escapeValue: false },
});

export function setLanguage(lng: 'en' | 'zh-TW'): void {
  void i18n.changeLanguage(lng);
  document.documentElement.lang = lng === 'zh-TW' ? 'zh-Hant' : 'en';
  try {
    localStorage.setItem('a320.lang', lng);
  } catch {
    // 私密模式：忽略
  }
}

export default i18n;
